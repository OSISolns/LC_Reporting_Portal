const cellBorder = {
  top: { style: 'thin', color: { argb: LC_BRAND.BORDER_SLATE } },
  bottom: { style: 'thin', color: { argb: LC_BRAND.BORDER_SLATE } },
  left: { style: 'thin', color: { argb: LC_BRAND.BORDER_SLATE } },
  right: { style: 'thin', color: { argb: LC_BRAND.BORDER_SLATE } },
};

const thickBottomBorder = {
  top: { style: 'thin', color: { argb: LC_BRAND.BORDER_SLATE } },
  bottom: { style: 'medium', color: { argb: LC_BRAND.DARK_BANNER } },
  left: { style: 'thin', color: { argb: LC_BRAND.BORDER_SLATE } },
  right: { style: 'thin', color: { argb: LC_BRAND.BORDER_SLATE } },
};

/**
 * Applies Legacy Clinics executive styling to a single worksheet.
 */
export const styleWorksheet = ({
  worksheet,
  title = 'LEGACY CLINICS — OPERATIONAL REPORT',
  subtitle = '',
  columns = [],
  data = [],
  metadata = [],
  summaryMetrics = [],
  user = null,
}) => {
  worksheet.views = [{ showGridLines: true }];
  const colCount = Math.max(columns.length, 2);
  const endColLetter = worksheet.getColumn(colCount).letter;

  // 1. Corporate Title Banner (Row 1)
  worksheet.mergeCells(`A1:${endColLetter}1`);
  const titleCell = worksheet.getCell('A1');
  titleCell.value = title.toUpperCase();
  titleCell.font = { name: 'Calibri', size: 15, bold: true, color: { argb: LC_BRAND.WHITE } };
  titleCell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: LC_BRAND.DARK_BANNER } };
  titleCell.alignment = { vertical: 'middle', horizontal: 'center' };
  worksheet.getRow(1).height = 36;

  // 2. Subtitle & Timestamp Banner (Row 2)
  const nowStr = new Date().toLocaleString('en-GB', {
    year: 'numeric',
    month: 'short',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit'
  });
  const subText = subtitle ? `${subtitle} | Generated: ${nowStr}` : `Generated: ${nowStr} | Lumina Logistics Hub`;

  worksheet.mergeCells(`A2:${endColLetter}2`);
  const subCell = worksheet.getCell('A2');
  subCell.value = subText;
  subCell.font = { name: 'Calibri', size: 10, bold: true, color: { argb: LC_BRAND.WHITE } };
  subCell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: LC_BRAND.PRIMARY } };
  subCell.alignment = { vertical: 'middle', horizontal: 'center' };
  worksheet.getRow(2).height = 22;

  // Spacer
  worksheet.addRow([]);
  let currentRow = 4;

  // 3. Metadata Section
  const defaultMeta = [
    ['Organization', 'Legacy Clinics Kigali — Operations & Logistics Command'],
    ['Generated By', user?.full_name || user?.username || 'Authorized Operational User'],
    ['Security Classification', 'CONFIDENTIAL — FOR INTERNAL USE ONLY'],
    ['Record Count', `${data.length.toLocaleString()} verified entries`],
    ...metadata
  ];

  defaultMeta.forEach(([label, val]) => {
    const row = worksheet.addRow([label, val]);
    row.getCell(1).font = { name: 'Calibri', size: 9.5, bold: true, color: { argb: LC_BRAND.DARK_BANNER } };
    row.getCell(1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: LC_BRAND.LIGHT_ACCENT } };
    row.getCell(1).border = cellBorder;
    row.getCell(2).font = { name: 'Calibri', size: 9.5, color: { argb: LC_BRAND.TEXT_MAIN } };
    row.getCell(2).border = cellBorder;
    row.height = 20;
    currentRow++;
  });

  // 4. Summary Metrics Cards (if any)
  if (summaryMetrics.length > 0) {
    worksheet.addRow([]);
    currentRow++;
    const metricLabels = summaryMetrics.map(m => m.label);
    const metricValues = summaryMetrics.map(m => m.value);

    const lblRow = worksheet.addRow(metricLabels);
    lblRow.height = 18;
    lblRow.eachCell((cell) => {
      cell.font = { name: 'Calibri', size: 9, bold: true, color: { argb: LC_BRAND.TEXT_MUTED } };
      cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: LC_BRAND.ACCENT_TEAL } };
      cell.alignment = { horizontal: 'center', vertical: 'middle' };
      cell.border = cellBorder;
    });

    const valRow = worksheet.addRow(metricValues);
    valRow.height = 24;
    valRow.eachCell((cell) => {
      cell.font = { name: 'Calibri', size: 12, bold: true, color: { argb: LC_BRAND.PRIMARY } };
      cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: LC_BRAND.WHITE } };
      cell.alignment = { horizontal: 'center', vertical: 'middle' };
      cell.border = cellBorder;
    });
    currentRow += 2;
  }

  // Spacer before table
  worksheet.addRow([]);
  currentRow++;

  // 5. Table Header Row
  const headerLabels = columns.map(c => c.header || c.key);
  const headerRow = worksheet.addRow(headerLabels);
  headerRow.height = 26;
  headerRow.eachCell((cell, colIndex) => {
    cell.font = { name: 'Calibri', size: 10.5, bold: true, color: { argb: LC_BRAND.WHITE } };
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: LC_BRAND.PRIMARY } };
    cell.alignment = {
      vertical: 'middle',
      horizontal: columns[colIndex - 1]?.alignment || 'left',
      wrapText: true
    };
    cell.border = thickBottomBorder;
  });
  currentRow++;

  // 6. Data Rows
  data.forEach((item, dataIndex) => {
    const rowValues = columns.map(c => {
      if (typeof c.render === 'function') {
        return c.render(item);
      }
      return item[c.key] ?? '—';
    });

    const dataRow = worksheet.addRow(rowValues);
    dataRow.height = 21;
    const isEven = dataIndex % 2 === 0;

    dataRow.eachCell((cell, colIndex) => {
      const colDef = columns[colIndex - 1] || {};
      cell.border = cellBorder;
      cell.font = { name: 'Calibri', size: 10, color: { argb: LC_BRAND.TEXT_MAIN } };
      cell.alignment = {
        vertical: 'middle',
        horizontal: colDef.alignment || 'left'
      };

      if (colDef.numFmt) {
        cell.numFmt = colDef.numFmt;
      }

      // Zebra striping
      if (!isEven) {
        cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: LC_BRAND.ZEBRA_FILL } };
      }

      // Status pill coloring if defined
      if (colDef.isStatus && typeof cell.value === 'string') {
        const valUpper = cell.value.toUpperCase();
        if (['AVAILABLE', 'ACTIVE', 'COMPLETED', 'PASSED', 'PAID', 'GOOD'].some(s => valUpper.includes(s))) {
          cell.font = { name: 'Calibri', size: 10, bold: true, color: { argb: LC_BRAND.STATUS_GREEN_TXT } };
          cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: LC_BRAND.STATUS_GREEN_BG } };
        } else if (['MAINTENANCE', 'PENDING', 'IN PROGRESS', 'IN USE', 'WARNING', 'REFILL RECOMMENDED'].some(s => valUpper.includes(s))) {
          cell.font = { name: 'Calibri', size: 10, bold: true, color: { argb: LC_BRAND.STATUS_AMBER_TXT } };
          cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: LC_BRAND.STATUS_AMBER_BG } };
        } else if (['CRITICAL', 'OUT OF SERVICE', 'EXPIRED', 'FAILED', 'REJECTED', 'DEFECT', 'IMMEDIATE REFUEL'].some(s => valUpper.includes(s))) {
          cell.font = { name: 'Calibri', size: 10, bold: true, color: { argb: LC_BRAND.STATUS_RED_TXT } };
          cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: LC_BRAND.STATUS_RED_BG } };
        }
      }
    });
    currentRow++;
  });

  // 7. Auto Column Width Tuning (Calculated dynamically)
  columns.forEach((colDef, idx) => {
    const col = worksheet.getColumn(idx + 1);
    let maxLen = colDef.header ? colDef.header.length : 12;

    // Check data lengths
    data.forEach(item => {
      let val = '';
      if (typeof colDef.render === 'function') {
        val = colDef.render(item);
      } else {
        val = item[colDef.key];
      }
      if (val !== null && val !== undefined) {
        const str = String(val);
        if (str.length > maxLen && str.length < 70) {
          maxLen = str.length;
        }
      }
    });

    const definedWidth = colDef.width || Math.max(maxLen + 4, 13);
    col.width = Math.min(Math.max(definedWidth, 12), 65);
  });
};

/**
 * Primary Export Utility: Generates and downloads a single-sheet Legacy Clinics Excel Report.
 */
export const exportToLegacyExcel = async ({
  title,
  subtitle,
  filename,
  sheetName = 'Operational Report',
  columns,
  data,
  metadata = [],
  summaryMetrics = [],
  user = null,
}) => {
  const toastId = toast.loading(`Generating Legacy Clinics ${title || 'Excel'} Report...`);
  try {
    const workbook = new ExcelJS.Workbook();
    workbook.creator = 'Lumina Logistics Command — Legacy Clinics Kigali';
    workbook.lastModifiedBy = user?.full_name || user?.username || 'Operations Officer';
    workbook.created = new Date();

    const worksheet = workbook.addWorksheet(sheetName.slice(0, 31)); // Excel limits sheet names to 31 chars
    styleWorksheet({
      worksheet,
      title,
      subtitle,
      columns,
      data,
      metadata,
      summaryMetrics,
      user,
    });

    const buffer = await workbook.xlsx.writeBuffer();
    const blob = new Blob([buffer], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' });
    const link = document.createElement('a');
    link.href = URL.createObjectURL(blob);

    const dateStamp = new Date().toISOString().slice(0, 10);
    const safeName = (filename || title || 'Legacy_Clinics_Report')
      .replace(/[^a-zA-Z0-9_\-]/g, '_')
      .replace(/_+/g, '_');
    link.download = `${safeName}_${dateStamp}.xlsx`;
    link.click();
    URL.revokeObjectURL(link.href);

    toast.success(`Exported ${title} to Excel!`, { id: toastId });
  } catch (err) {
    console.error('Legacy Clinics Excel Export error:', err);
    toast.error('Failed to export Excel report. Please try again.', { id: toastId });
  }
};

/**
 * Multi-Sheet Export Utility: Generates an executive workbook containing multiple sheets.
 */
export const exportMultiSheetLegacyExcel = async ({
  title = 'LEGACY CLINICS — EXECUTIVE REPORT',
  filename = 'Legacy_Clinics_Executive_Report',
  sheets = [],
  user = null,
}) => {
  const toastId = toast.loading(`Generating Legacy Clinics Executive Report...`);
  try {
    const workbook = new ExcelJS.Workbook();
    workbook.creator = 'Lumina Logistics Command — Legacy Clinics Kigali';
    workbook.lastModifiedBy = user?.full_name || user?.username || 'Operations Officer';
    workbook.created = new Date();

    sheets.forEach((s) => {
      const sheetName = (s.sheetName || 'Sheet').slice(0, 31);
      const ws = workbook.addWorksheet(sheetName);
      styleWorksheet({
        worksheet: ws,
        title: s.title || title,
        subtitle: s.subtitle || '',
        columns: s.columns || [],
        data: s.data || [],
        metadata: s.metadata || [],
        summaryMetrics: s.summaryMetrics || [],
        user,
      });
    });

    const buffer = await workbook.xlsx.writeBuffer();
    const blob = new Blob([buffer], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' });
    const link = document.createElement('a');
    link.href = URL.createObjectURL(blob);

    const dateStamp = new Date().toISOString().slice(0, 10);
    const safeName = filename.replace(/[^a-zA-Z0-9_\-]/g, '_').replace(/_+/g, '_');
    link.download = `${safeName}_${dateStamp}.xlsx`;
    link.click();
    URL.revokeObjectURL(link.href);

    toast.success(`Executive Excel Report downloaded!`, { id: toastId });
  } catch (err) {
    console.error('Multi-sheet Excel export error:', err);
    toast.error('Failed to generate multi-sheet Excel report.', { id: toastId });
  }
};
