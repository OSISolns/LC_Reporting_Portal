  PRIMARY: '1B669E',         // Legacy Brand Blue / Cyan Teal
  PRIMARY_DEEP: '0F4C81',    // Deep Blue
  LIGHT_ACCENT: 'E0F2FE',    // Light Ice / Sky Blue Fill
  ACCENT_TEAL: 'CCECEF',     // Subtle Teal Highlight
  ZEBRA_FILL: 'F8FAFC',      // Alternating Data Row Off-White Fill
  BORDER_SLATE: 'CBD5E1',    // Crisp Thin Slate Border
  WHITE: 'FFFFFF',
  TEXT_MAIN: '0F172A',
  TEXT_MUTED: '475569',
  STATUS_GREEN_BG: 'DCFCE7',
  STATUS_GREEN_TXT: '15803D',
  STATUS_AMBER_BG: 'FEF3C7',
  STATUS_AMBER_TXT: 'B45309',
  STATUS_RED_BG: 'FEE2E2',
  STATUS_RED_TXT: 'B91C1C',
